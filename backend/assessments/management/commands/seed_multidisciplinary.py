"""
Management command: seed_multidisciplinary
-------------------------------------------
Generates high-quality MCQ assessments for diverse academic fields so that
every user — regardless of their discipline — finds relevant practice content
on EduReach.

Fields covered:
  medicine, nursing, pharmacy, chemistry, biology, architecture, law,
  business, accounting, computer_science, agriculture, education

Each topic → 1 Assessment with 12 MCQ questions generated by AI.

Usage:
    python manage.py seed_multidisciplinary --dry-run
    python manage.py seed_multidisciplinary                        # all fields
    python manage.py seed_multidisciplinary --fields medicine,nursing,law
    python manage.py seed_multidisciplinary --fields chemistry --update

Notes:
    - Skips assessments that already exist (by title) unless --update is passed.
    - Costs ~50–80K tokens total for all fields at 12q each (~$0.05-0.15).
    - Each generated question is reviewed for quality: must have 4 options
      and a correct answer; questions that fail are discarded.
"""

